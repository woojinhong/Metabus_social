-- TEST-SCOPE ONLY. These fixtures are not final product tables or an operating migration.
CREATE TABLE SPIKE_ACCOUNT_GUARD (
  ACCOUNT_ID UUID PRIMARY KEY,
  LOGIN_NAME VARCHAR(80) NOT NULL UNIQUE,
  ACCOUNT_STATUS VARCHAR(24) NOT NULL
    CHECK (ACCOUNT_STATUS IN ('ACTIVE', 'SUSPENDED', 'ACCESS_CLOSED')),
  ROW_VERSION BIGINT NOT NULL,
  SESSION_EPOCH BIGINT NOT NULL,
  AUTHORIZATION_EPOCH BIGINT NOT NULL,
  BUSINESS_VALUE INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE SPIKE_AUDIT_FIXTURE (
  AUDIT_ID UUID PRIMARY KEY,
  ACTION_NAME VARCHAR(80) NOT NULL,
  TARGET_REF UUID NOT NULL,
  OUTCOME VARCHAR(24) NOT NULL CHECK (OUTCOME IN ('REQUESTED', 'SUCCEEDED', 'FAILED')),
  CORRELATION_REF UUID NOT NULL,
  CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX SPIKE_AUDIT_CORRELATION_IX
  ON SPIKE_AUDIT_FIXTURE (CORRELATION_REF, ACTION_NAME, OUTCOME);

CREATE TABLE SPIKE_SESSION_ACTION (
  ACTION_ID UUID PRIMARY KEY,
  IDEMPOTENCY_KEY VARCHAR(100) NOT NULL UNIQUE,
  SESSION_REF VARCHAR(100) NOT NULL,
  ACTION_STATE VARCHAR(24) NOT NULL CHECK (ACTION_STATE IN ('PENDING', 'SUCCEEDED', 'FAILED')),
  RESULT_VERSION BIGINT NOT NULL,
  UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
